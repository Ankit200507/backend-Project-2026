export function getStatsData() {
    const total = MOCK_PROPERTIES.length;
    const registered = MOCK_PROPERTIES.filter(p => p.status === 'registered').length;
    const pending = MOCK_PROPERTIES.filter(p => p.status === 'pending').length;
    const disputed = MOCK_PROPERTIES.filter(p => p.status === 'disputed').length;
    const totalArea = MOCK_PROPERTIES.reduce((sum, p) => sum + p.area, 0);
    const owners = new Set(MOCK_PROPERTIES.map(p => p.ownerEmail)).size;
    return { totalParcels: total, registered, pending, disputed, totalArea, totalOwners: owners };
}

export function getPropertyById(id: string): LandRecord | undefined {
    return MOCK_PROPERTIES.find(p => p.id === id);
}

export function getPropertiesByOwner(email: string): LandRecord[] {
    return MOCK_PROPERTIES.filter(p => p.ownerEmail === email);
}

